const STORAGE_KEY = 'kubelearn.lang';

// The saved choice, or the browser language when it is one we support.
export const initialLanguage = () => {
  try {
    const saved = window.localStorage.getItem(STORAGE_KEY);
    if (LANGUAGES.some((language) => language.id === saved)) return saved;
  } catch (err) {
    // Storage unavailable: fall through to the browser language.
  }
  const browser = (window.navigator.language || 'en').slice(0, 2).toLowerCase();
  return LANGUAGES.some((language) => language.id === browser) ? browser : 'en';
};

export const saveLanguage = (lang) => {
  try {
    window.localStorage.setItem(STORAGE_KEY, lang);
  } catch (err) {
    // Not being able to remember the choice is harmless.
  }
};

