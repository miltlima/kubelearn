// translator returns t(key, values): the text for key in lang, with {name}
// placeholders replaced by values.name.
export const translator = (lang) => (key, values = {}) => {
  const template = STRINGS[lang]?.[key] ?? STRINGS.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (match, name) => (name in values ? String(values[name]) : match));
};

